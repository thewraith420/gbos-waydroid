#!/usr/bin/env python3
"""gbos-secctx: let Android's binder security-context requests work on a kernel whose only LSM is AppArmor.

Android 17's keystore2 (and everything that talks to it, starting with odsign) asks binder to attach the caller's security
context to each call. On a kernel with AppArmor and no SELinux, binder always fails that request ("binder: ... failed to get
security context", error -22), because AppArmor does not implement the hook binder uses to find the caller's label. Android's
`odsign` then aborts in a loop and the boot never gets past the boot animation / black screen.

The real fix is a small AppArmor kernel patch (kernel/README.md). If rebuilding the kernel is not an option, this module does
the same job without one: a kprobe on apparmor_secid_to_secctx() answers the one lookup that can never succeed with the
Waydroid AppArmor profile's name. Every other lookup runs the original code.

    gbos-secctx.py build     --tree KERNEL_BUILD_TREE --out DIR     build + self-verify (no root)
    gbos-secctx.py verify    --tree KERNEL_BUILD_TREE --out DIR
    sudo gbos-secctx.py install   --out DIR                          install, load now and at every boot
    sudo gbos-secctx.py uninstall
         gbos-secctx.py status

Needs: x86-64, CONFIG_KPROBES, AppArmor built in, modules allowed unsigned (same limits as gbos-vexemu.py). Not needed (and
refused) on a kernel that already carries the AppArmor patch. Python 3.8+, standard library only.
"""
import argparse
import importlib.util
import json
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
_spec = importlib.util.spec_from_file_location("gbos_vexemu_lib", os.path.join(HERE, "gbos-vexemu.py"))
lib = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(lib)

MOD = "gbos_secctx"
SUBDIR = "updates/gbos-secctx"
LOADCONF = "/etc/modules-load.d/gbos-secctx.conf"
lib.MOD = MOD            # the shared verify step looks the module up by this name
die, say, run, tool, sha256, P = lib.die, lib.say, lib.run, lib.tool, lib.sha256, lib.P


def already_fixed():
    try:
        return any(l.rstrip().endswith(" apparmor_cred_getsecid") for l in open("/proc/kallsyms"))
    except OSError:
        return False


def loaded():
    return os.path.isdir("/sys/module/" + MOD)


def cmd_build(a):
    tree = os.path.abspath(a.tree)
    info = lib.tree_info(tree)
    cfg = info["cfg"]
    for opt, why in (("CONFIG_X86_64=y", "x86-64 kernels only"), ("CONFIG_MODULES=y", "this kernel has no module support"),
                     ("CONFIG_KPROBES=y", "this kernel has no kprobes, which the module needs"),
                     ("CONFIG_SECURITY_APPARMOR=y", "AppArmor is not built in, so there is nothing to fix")):
        if opt not in cfg:
            die(why)
    if "CONFIG_MODULE_SIG_FORCE=y" in cfg:
        die("this kernel only loads signed modules; an unsigned module would be refused")
    if not a.allow_other:
        if info["release"] != os.uname().release:
            die("the tree is for %s but %s is running (use --allow-other to build for another machine)" % (info["release"], os.uname().release))
        if run(["uname", "-v"]).stdout.strip() != info["version"]:
            die("same release string but a different build; the module would not match the kernel's symbol checksums")
        if already_fixed():
            die("this kernel already has the AppArmor cred_getsecid fix; the module is not needed")
    out = os.path.abspath(a.out)
    work = os.path.join(out, "work")
    os.makedirs(out, exist_ok=True)
    if os.path.isdir(work):
        shutil.rmtree(work)
    os.makedirs(work)
    shutil.copy2(os.path.join(HERE, "secctx", MOD + ".c"), work)
    with open(os.path.join(work, "Makefile"), "w") as f:
        f.write("# generated by gbos-secctx.py\nobj-m += %s.o\n" % MOD)
    cmd = ["make", "-C", tree, "M=" + work, "modules"]
    if info["clang"]:
        if not (tool("clang") and tool("ld.lld")):
            die("the kernel was built with clang; install clang and lld (the same major version if you can) and retry")
        cmd.insert(1, "LLVM=1")
    say("building %s for %s with %s" % (MOD, info["release"], "clang/LLVM" if info["clang"] else "the default compiler"))
    r = run((["nice", "-n", "10"] if tool("nice") else []) + cmd)
    open(os.path.join(out, "build.log"), "w").write(r.stdout + r.stderr)
    if r.returncode != 0:
        die("the build failed; see %s\n%s" % (os.path.join(out, "build.log"), (r.stdout + r.stderr)[-1500:]))
    os.makedirs(os.path.join(out, "modules"), exist_ok=True)
    dst = os.path.join(out, "modules", MOD + ".ko")
    shutil.copy2(os.path.join(work, MOD + ".ko"), dst)
    with open(os.path.join(out, "manifest.json"), "w") as f:
        json.dump({"release": info["release"], "version": info["version"], "sha256": sha256(dst)}, f, indent=2)
    return lib.do_verify(tree, out, info)


def cmd_verify(a):
    return lib.do_verify(os.path.abspath(a.tree), os.path.abspath(a.out))


def cmd_install(a):
    lib.need_root()
    out = os.path.abspath(a.out)
    try:
        man = json.load(open(os.path.join(out, "manifest.json")))
    except (OSError, ValueError):
        die("%s has no manifest.json: run `build` first" % out)
    rel = man["release"]
    if lib.ROOT == "/":
        if os.uname().release != rel or run(["uname", "-v"]).stdout.strip() != man["version"]:
            die("this module was built for %s (%s), which is not the running kernel" % (rel, man["version"]))
        if already_fixed():
            die("this kernel already has the AppArmor cred_getsecid fix; the module is not needed")
    src = os.path.join(out, "modules", MOD + ".ko")
    if not os.path.isfile(src) or sha256(src) != man["sha256"]:
        die("%s is missing or does not match the manifest (rebuild)" % src)
    dest = P("/lib/modules/%s/%s" % (rel, SUBDIR))
    os.makedirs(dest, exist_ok=True)
    shutil.copyfile(src, os.path.join(dest, MOD + ".ko"))
    os.chmod(os.path.join(dest, MOD + ".ko"), 0o644)
    lib.depmod(rel)
    os.makedirs(os.path.dirname(P(LOADCONF)), exist_ok=True)
    with open(P(LOADCONF), "w") as f:
        f.write("# written by gbos-secctx.py: answer binder's security-context lookups on an AppArmor-only kernel\n%s\n" % MOD)
    say("installed %s, ran depmod, and set it to load at every boot (%s)." % (os.path.join(dest, MOD + ".ko"), LOADCONF))
    if lib.ROOT == "/" and not a.no_load and not loaded():
        r = run([tool("modprobe") or "modprobe", MOD])
        if r.returncode != 0:
            die("installed, but loading failed: %s" % (r.stderr.strip() or r.stdout.strip()))
        say("loaded now. Restart the container (waydroid session stop; systemctl restart waydroid-container) so the services retry.")
    say("Undo: sudo %s uninstall" % sys.argv[0])
    return 0


def cmd_uninstall(a):
    lib.need_root()
    rel = a.release or os.uname().release
    if lib.ROOT == "/" and loaded():
        r = run([tool("modprobe") or "modprobe", "-r", MOD])
        say("unloaded." if r.returncode == 0 else "could not unload (%s)" % r.stderr.strip())
    dest = P("/lib/modules/%s/%s" % (rel, SUBDIR))
    if os.path.isdir(dest):
        shutil.rmtree(dest)
        try:
            os.rmdir(os.path.dirname(dest))
        except OSError:
            pass
        lib.depmod(rel)
    if os.path.isfile(P(LOADCONF)):
        os.remove(P(LOADCONF))
    say("removed the module and its load-at-boot entry.")
    return 0


def cmd_status(a):
    rel = os.uname().release
    dest = P("/lib/modules/%s/%s" % (rel, SUBDIR))
    say("kernel %s" % rel)
    say("kernel has the AppArmor fix itself: %s" % ("yes (module not needed)" if already_fixed() else "no"))
    say("installed: %s" % ("yes" if os.path.isfile(os.path.join(dest, MOD + ".ko")) else "no"))
    say("at boot:   %s" % ("yes" if os.path.isfile(P(LOADCONF)) else "no"))
    say("loaded:    %s" % ("yes" if loaded() else "no"))
    if loaded():
        try:
            say("lookups answered so far: %s" % open("/sys/module/%s/parameters/served" % MOD).read().strip())
        except OSError:
            pass
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default="/", help=argparse.SUPPRESS)
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build")
    b.add_argument("--tree", required=True)
    b.add_argument("--out", required=True)
    b.add_argument("--allow-other", action="store_true")
    b.set_defaults(fn=cmd_build)
    v = sub.add_parser("verify")
    v.add_argument("--tree", required=True)
    v.add_argument("--out", required=True)
    v.set_defaults(fn=cmd_verify)
    i = sub.add_parser("install")
    i.add_argument("--out", required=True)
    i.add_argument("--no-load", action="store_true")
    i.set_defaults(fn=cmd_install)
    u = sub.add_parser("uninstall")
    u.add_argument("--release")
    u.set_defaults(fn=cmd_uninstall)
    s = sub.add_parser("status")
    s.set_defaults(fn=cmd_status)
    a = ap.parse_args()
    lib.ROOT = os.path.abspath(a.root)
    return a.fn(a)


if __name__ == "__main__":
    sys.exit(main())
