#!/usr/bin/env python3
"""gbos-netfilter-legacy: add the legacy iptables tables to a kernel that was built without them.

Android's netd talks to the LEGACY iptables API (the filter, nat, mangle and raw tables). Distribution kernels have
it; a trimmed custom kernel may not, and then Android boots without a working network. The real fix is a kernel
config change (see `gbos-install.py kernel-fragment`), but if rebuilding the kernel is not an option, the missing
pieces are all loadable modules and can be added to the kernel you already run:

    gbos-netfilter-legacy.py build     --tree KERNEL_BUILD_TREE --out DIR      build and self-verify (no root)
    gbos-netfilter-legacy.py verify    --tree KERNEL_BUILD_TREE --out DIR      re-run the checks on a build
    sudo gbos-netfilter-legacy.py install   --out DIR                          install into updates/, run depmod
    sudo gbos-netfilter-legacy.py uninstall                                    remove them again
         gbos-netfilter-legacy.py status

KERNEL_BUILD_TREE is the tree your running kernel was BUILT in (or a copy of it): it must contain .config,
Module.symvers, include/generated/ and the netfilter sources of that same build (net/netfilter/x_tables.c ...).
It must be the very build that is running: the modules are checked against it and refused otherwise.

How it works. `x_tables` (a module on such kernels) has a switch, NETFILTER_XTABLES_LEGACY, that compiles in a few more
exported functions. It changes no struct and no existing export, so a rebuilt x_tables.ko is a strict superset of the one
running. It is rebuilt together with ip_tables, ip6_tables and the eight iptable_* / ip6table_* modules, with that switch
defined, against the running kernel's own headers and symbol checksums. `build` then proves compatibility before anything
is installed: same build, same vermagic, every existing x_tables export has an unchanged checksum, every imported symbol
resolves to the checksum the kernel exports. `install` puts the files in /lib/modules/<release>/updates/gbos-netfilter/
(depmod prefers `updates/`), leaves the originals untouched, and needs a REBOOT because x_tables is in use.

Taint: the modules are unsigned. That is accepted when module signatures are not enforced (the usual custom-kernel
setup, CONFIG_MODULE_SIG_FORCE unset) and marks the kernel as tainted. Secure Boot with enforced signatures would refuse them.

Python 3.8+, standard library only. Needs make and the compiler the kernel was built with (clang+lld for most custom kernels).
"""
import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys

MODULES = [
    "net/netfilter/x_tables",
    "net/ipv4/netfilter/ip_tables", "net/ipv4/netfilter/iptable_filter", "net/ipv4/netfilter/iptable_nat",
    "net/ipv4/netfilter/iptable_mangle", "net/ipv4/netfilter/iptable_raw",
    "net/ipv6/netfilter/ip6_tables", "net/ipv6/netfilter/ip6table_filter", "net/ipv6/netfilter/ip6table_nat",
    "net/ipv6/netfilter/ip6table_mangle", "net/ipv6/netfilter/ip6table_raw",
]
EXTRA_FILES = ["net/netfilter/xt_repldata.h"]          # included by relative path from ip_tables.c / ip6_tables.c
SUBDIR = "updates/gbos-netfilter"
MAKEFILE = """# Generated by gbos-netfilter-legacy.py. The directory layout mirrors the kernel tree because some
# sources include siblings by relative path. The switch below is the only change to the kernel's own code.
obj-m += %(objs)s
ccflags-y += -DCONFIG_NETFILTER_XTABLES_LEGACY=1
"""
ROOT = "/"


def P(p):
    return p if ROOT == "/" else os.path.join(ROOT, p.lstrip("/"))


def die(msg):
    sys.exit("gbos-netfilter-legacy: " + msg)


def say(msg):
    print(msg, flush=True)


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for blk in iter(lambda: f.read(1 << 20), b""):
            h.update(blk)
    return h.hexdigest()


def tool(name):
    for d in os.environ.get("PATH", "").split(os.pathsep) + ["/sbin", "/usr/sbin"]:
        p = os.path.join(d, name)
        if os.path.isfile(p) and os.access(p, os.X_OK):
            return p
    return None


def read_symvers(path):
    """{symbol: (crc, module)} from a Module.symvers file."""
    out = {}
    with open(path) as f:
        for line in f:
            p = line.rstrip("\n").split("\t")
            if len(p) >= 3:
                out[p[1]] = (p[0], p[2])
    return out


def dump_versions(ko):
    """{symbol: crc} a module expects from the kernel (its __versions section)."""
    r = subprocess.run([tool("modprobe") or "modprobe", "--dump-modversions", ko], capture_output=True, text=True)
    d = {}
    for line in r.stdout.splitlines():
        p = line.split()
        if len(p) == 2:
            d[p[1]] = p[0]
    return d


def tree_info(tree):
    need = [".config", "Module.symvers", "include/generated/utsrelease.h", "include/generated/utsversion.h",
            "scripts/mod/modpost", "Makefile"]
    miss = [n for n in need if not os.path.exists(os.path.join(tree, n))]
    if miss:
        die("%s is not a built kernel tree; missing: %s" % (tree, ", ".join(miss)))
    rel = re.search(r'"(.*)"', open(os.path.join(tree, "include/generated/utsrelease.h")).read()).group(1)
    ver = re.search(r'UTS_VERSION "(.*)"', open(os.path.join(tree, "include/generated/utsversion.h")).read()).group(1)
    cfg = open(os.path.join(tree, ".config")).read()
    return {"release": rel, "version": ver, "clang": "CONFIG_CC_IS_CLANG=y" in cfg,
            "legacy_already": "CONFIG_NETFILTER_XTABLES_LEGACY=y" in cfg,
            "xtables_builtin": "CONFIG_NETFILTER_XTABLES=y" in cfg}


# ------------------------------------------------------------------------------------------ build
def cmd_build(a):
    tree = os.path.abspath(a.tree)
    info = tree_info(tree)
    if info["legacy_already"]:
        die("this kernel already has NETFILTER_XTABLES_LEGACY=y; nothing to add")
    if info["xtables_builtin"]:
        die("x_tables is built into this kernel (CONFIG_NETFILTER_XTABLES=y), so it cannot be replaced by a module; "
            "rebuild the kernel with `gbos-install.py kernel-fragment`")
    running = os.uname().release
    if not a.allow_other and info["release"] != running:
        die("the tree is for %s but %s is running (use --allow-other to build for another machine)" % (info["release"], running))
    if not a.allow_other:
        rv = subprocess.run(["uname", "-v"], capture_output=True, text=True).stdout.strip()
        if rv != info["version"]:
            die("same release string but a different build:\n  tree:    %s\n  running: %s\n"
                "The modules would not match the running kernel's symbol checksums." % (info["version"], rv))
    src = os.path.abspath(a.source) if a.source else tree
    for m in MODULES:
        if not os.path.isfile(os.path.join(src, m + ".c")):
            die("missing source %s.c under %s" % (m, src))
    out = os.path.abspath(a.out)
    work = os.path.join(out, "work")
    if os.path.isdir(work):
        shutil.rmtree(work)
    for m in MODULES:
        os.makedirs(os.path.join(work, os.path.dirname(m)), exist_ok=True)
        shutil.copy2(os.path.join(src, m + ".c"), os.path.join(work, m + ".c"))
    for x in EXTRA_FILES:
        os.makedirs(os.path.join(work, os.path.dirname(x)), exist_ok=True)
        shutil.copy2(os.path.join(src, x), os.path.join(work, x))
    with open(os.path.join(work, "Makefile"), "w") as f:
        f.write(MAKEFILE % {"objs": " \\\n    ".join(m + ".o" for m in MODULES)})
    cmd = ["make", "-C", tree, "M=" + work, "-j%d" % a.jobs, "modules"]
    if info["clang"]:
        if not (tool("clang") and tool("ld.lld")):
            die("the kernel was built with clang; install clang and lld (the same major version if you can) and retry")
        cmd.insert(1, "LLVM=1")
    say("building %d modules for %s with %s" % (len(MODULES), info["release"], "clang/LLVM" if info["clang"] else "the default compiler"))
    pre = (["nice", "-n", "10"] if tool("nice") else []) + (["ionice", "-c3"] if tool("ionice") else [])
    r = subprocess.run(pre + cmd, capture_output=True, text=True)
    open(os.path.join(out, "build.log"), "w").write(r.stdout + r.stderr)
    if r.returncode != 0:
        die("the build failed; see %s\n%s" % (os.path.join(out, "build.log"), (r.stdout + r.stderr)[-1200:]))
    kos = os.path.join(out, "modules")
    os.makedirs(kos, exist_ok=True)
    manifest = {"release": info["release"], "version": info["version"], "modules": {}}
    for m in MODULES:
        dst = os.path.join(kos, os.path.basename(m) + ".ko")
        shutil.copy2(os.path.join(work, m + ".ko"), dst)
        manifest["modules"][os.path.basename(m) + ".ko"] = sha256(dst)
    shutil.copy2(os.path.join(work, "Module.symvers"), os.path.join(out, "Module.symvers.new"))
    with open(os.path.join(out, "manifest.json"), "w") as f:
        json.dump(manifest, f, indent=2)
    return do_verify(tree, out, info)


# ------------------------------------------------------------------------------------------ verify
def do_verify(tree, out, info=None):
    info = info or tree_info(tree)
    ok = True

    def check(good, text):
        nonlocal ok
        say("  [%s] %s" % ("ok" if good else "FAIL", text))
        ok = ok and good

    say("verifying the build in %s" % out)
    kos = {m: os.path.join(out, "modules", os.path.basename(m) + ".ko") for m in MODULES}
    check(all(os.path.isfile(p) for p in kos.values()), "all %d modules present" % len(MODULES))
    # 1. vermagic
    vm = {}
    for m, p in kos.items():
        r = subprocess.run([tool("modinfo") or "modinfo", "-F", "vermagic", p], capture_output=True, text=True)
        vm[os.path.basename(m)] = r.stdout.strip()
    want = info["release"] + " "
    check(all(v.startswith(want) for v in vm.values()) and len(set(vm.values())) == 1,
          "vermagic is '%s' for every module" % next(iter(vm.values()), "?"))
    # 2. x_tables: existing exports unchanged, only additions
    old = {s: c for s, (c, mod) in read_symvers(os.path.join(tree, "Module.symvers")).items() if mod == "net/netfilter/x_tables"}
    new_all = read_symvers(os.path.join(out, "Module.symvers.new"))
    new = {s: c for s, (c, mod) in new_all.items() if mod == "net/netfilter/x_tables"}
    changed = [s for s in old if new.get(s) != old[s]]
    added = sorted(set(new) - set(old))
    check(not changed, "all %d existing x_tables exports keep their checksum%s" % (len(old), "" if not changed else "; CHANGED: " + ", ".join(changed[:5])))
    say("         the rebuild adds %d exports: %s" % (len(added), ", ".join(added)))
    # 3. every import resolves to the checksum the kernel (or the new set) provides
    kernel = {s: c for s, (c, mod) in read_symvers(os.path.join(tree, "Module.symvers")).items()}
    provided = {s: c for s, (c, mod) in new_all.items()}       # what the new module set itself exports
    bad = []
    n = 0
    for m, p in kos.items():
        for sym, crc in dump_versions(p).items():
            n += 1
            if provided.get(sym) != crc and kernel.get(sym) != crc:
                bad.append((os.path.basename(m), sym, crc, kernel.get(sym)))
    check(not bad, "all %d imported symbols match the running kernel's checksums%s" % (n, "" if not bad else "; e.g. %s" % (bad[0],)))
    # 4. optional, on the target: against the modules that are actually installed
    inst = "/lib/modules/%s/kernel/net/netfilter" % info["release"]
    if os.path.isdir(P(inst)) and ROOT == "/":
        seen = {}
        for f in os.listdir(inst):
            if f.startswith("xt_") or f in ("nft_compat.ko.zst", "nft_compat.ko"):
                for sym, crc in dump_versions(os.path.join(inst, f)).items():
                    if sym in new:
                        seen.setdefault(sym, set()).add(crc)
        wrong = [s for s, v in seen.items() if v != {new[s]}]
        check(not wrong, "the installed xt_* modules expect exactly the checksums the new x_tables exports (%d symbols compared)" % len(seen))
    say("RESULT: %s" % ("verified; safe to install" if ok else "NOT VERIFIED; do not install"))
    return 0 if ok else 1


def cmd_verify(a):
    return do_verify(os.path.abspath(a.tree), os.path.abspath(a.out))


# ------------------------------------------------------------------------------------------ install / uninstall / status
def need_root():
    if ROOT == "/" and os.geteuid() != 0:
        die("this needs root: sudo %s" % " ".join(sys.argv))


def depmod(rel):
    if not tool("depmod"):
        die("depmod not found")
    cmd = [tool("depmod")] + (["-b", ROOT] if ROOT != "/" else []) + ["-a", rel]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        die("depmod failed: " + r.stderr.strip())


def cmd_install(a):
    need_root()
    out = os.path.abspath(a.out)
    try:
        man = json.load(open(os.path.join(out, "manifest.json")))
    except (OSError, ValueError):
        die("%s has no manifest.json: run `build` first" % out)
    rel = man["release"]
    if ROOT == "/":
        if os.uname().release != rel:
            die("these modules are for %s but %s is running" % (rel, os.uname().release))
        if subprocess.run(["uname", "-v"], capture_output=True, text=True).stdout.strip() != man["version"]:
            die("same release string, different build; refusing")
    for name, digest in man["modules"].items():
        p = os.path.join(out, "modules", name)
        if not os.path.isfile(p) or sha256(p) != digest:
            die("%s is missing or does not match the manifest (rebuild)" % name)
    dest = P("/lib/modules/%s/%s" % (rel, SUBDIR))
    os.makedirs(dest, exist_ok=True)
    for name in man["modules"]:
        shutil.copyfile(os.path.join(out, "modules", name), os.path.join(dest, name))
        os.chmod(os.path.join(dest, name), 0o644)
    shutil.copyfile(os.path.join(out, "manifest.json"), os.path.join(dest, "MANIFEST.json"))
    depmod(rel)
    say("installed %d modules into %s and ran depmod." % (len(man["modules"]), dest))
    say("The originals were not touched. x_tables is in use, so the new one takes over at the next boot: REBOOT.")
    say("Afterwards:  %s status      and      gbos-install.py check" % sys.argv[0])
    say("To undo:     sudo %s uninstall   (then reboot)" % sys.argv[0])
    return 0


def cmd_uninstall(a):
    need_root()
    rel = a.release or os.uname().release
    dest = P("/lib/modules/%s/%s" % (rel, SUBDIR))
    if not os.path.isdir(dest):
        say("nothing installed for %s" % rel)
        return 0
    shutil.rmtree(dest)
    try:
        os.rmdir(os.path.dirname(dest))                 # updates/ itself, only if now empty
    except OSError:
        pass
    depmod(rel)
    say("removed %s and ran depmod. Reboot to go back to the original x_tables." % dest)
    return 0


def cmd_status(a):
    rel = os.uname().release
    dest = P("/lib/modules/%s/%s" % (rel, SUBDIR))
    say("kernel %s" % rel)
    say("installed:  %s" % ("yes (%d files in %s)" % (len(os.listdir(dest)) - 1, dest) if os.path.isdir(dest) else "no"))
    for m in ("x_tables", "ip_tables", "iptable_filter", "iptable_nat", "iptable_mangle", "iptable_raw", "ip6table_filter"):
        r = subprocess.run([tool("modinfo") or "modinfo", "-n", m], capture_output=True, text=True)
        path = r.stdout.strip()
        loaded = os.path.isdir("/sys/module/" + m)
        say("  %-16s %-9s %s" % (m, "loaded" if loaded else "", path or "NOT AVAILABLE"))
    # Is the module that is loaded right now the new one? Compare the loaded srcversion with the installed file's.
    inst = os.path.join(dest, "x_tables.ko")
    want = subprocess.run([tool("modinfo") or "modinfo", "-F", "srcversion", inst], capture_output=True, text=True).stdout.strip() if os.path.isfile(inst) else ""
    try:
        have = open("/sys/module/x_tables/srcversion").read().strip()
    except OSError:
        have = ""
    legacy = subprocess.run(["sh", "-c", "grep -q ' xt_register_table' /proc/kallsyms && echo yes || echo no"],
                            capture_output=True, text=True).stdout.strip()
    say("legacy part (xt_register_table) present in the running kernel: %s" % legacy)
    if not os.path.isdir(dest):
        say("-> not installed")
    elif not have:
        say("-> installed; x_tables is not loaded yet, so the NEW one will be used the first time anything loads it "
            "(or run: sudo modprobe iptable_filter)")
    elif have == want:
        say("-> active: the loaded x_tables is the installed one")
    else:
        say("-> installed, but the OLD x_tables is still loaded (something loaded it before): reboot, or stop what uses it and `modprobe -r` it")
    return 0


def main():
    global ROOT
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default="/", help=argparse.SUPPRESS)
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build")
    b.add_argument("--tree", required=True)
    b.add_argument("--source", help="tree holding the netfilter sources, if not the build tree itself")
    b.add_argument("--out", required=True)
    b.add_argument("--jobs", type=int, default=2)
    b.add_argument("--allow-other", action="store_true", help="build for a kernel that is not the one running here")
    b.set_defaults(fn=cmd_build)
    v = sub.add_parser("verify")
    v.add_argument("--tree", required=True)
    v.add_argument("--out", required=True)
    v.set_defaults(fn=cmd_verify)
    i = sub.add_parser("install")
    i.add_argument("--out", required=True)
    i.set_defaults(fn=cmd_install)
    u = sub.add_parser("uninstall")
    u.add_argument("--release")
    u.set_defaults(fn=cmd_uninstall)
    s = sub.add_parser("status")
    s.set_defaults(fn=cmd_status)
    a = ap.parse_args()
    ROOT = os.path.abspath(a.root)
    return a.fn(a)


if __name__ == "__main__":
    sys.exit(main())
