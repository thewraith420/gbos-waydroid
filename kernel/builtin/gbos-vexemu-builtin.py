#!/usr/bin/env python3
"""gbos-vexemu-builtin: produce the BUILT-IN (=y) variant of gbos_vexemu as a kernel patch, for a kernel that has to emulate
GFNI / VAES / VPCLMULQDQ / AVX-VNNI / AVX-IFMA / SHA-NI from the very first userland process (bare-metal GBOS: Android's
first-stage init is itself GBOS userland and would die with SIGILL; a module loaded later is too late).

It does NOT change ../vexemu/gbos_vexemu.c. It derives the in-tree file from it by one asserted substitution
(module_init -> arch_initcall), so the code that the QEMU test bed validated is the code that goes in the kernel.

    gbos-vexemu-builtin.py gen   --tree KERNEL_SOURCE_TREE --out DIR [--patch PINNED_VEX_EMULATE_PATCH]
        writes   DIR/9209-gbos-vexemu-builtin.patch   our code only: Kconfig (default n), Makefile line, arch/x86/kernel/gbos_vexemu.c
                 DIR/churro_math.inc                  the third-party arithmetic, cut from the sha256-pinned patch (NOT part of the .patch)
        and dry-runs the patch against the tree (read-only).
    gbos-vexemu-builtin.py apply --tree TREE --out DIR     patch -p1 the .patch and copy churro_math.inc to arch/x86/kernel/ (a build step)
    gbos-vexemu-builtin.py check --tree TREE               confirm the tree carries the patch + the math file

Why the arithmetic is kept out of the patch: it is third-party code (project-churro, GPL-2.0). Same rule as the module:
fetch the pinned file, check its sha256, cut the math out at build time; nothing third-party is stored in our repos.
Kernel option: CONFIG_GBOS_VEXEMU (default n). Command line (built-in module parameters): gbos_vexemu.enabled=0|1,
gbos_vexemu.verbose=1, gbos_vexemu.runahead=0|1; counters in /sys/module/gbos_vexemu/parameters/stats.
"""
import argparse
import difflib
import hashlib
import importlib.util
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
KDIR = os.path.dirname(HERE)
SRC_C = os.path.join(KDIR, "vexemu", "gbos_vexemu.c")
PATCH_NAME = "9209-gbos-vexemu-builtin.patch"          # the kernel session assigns the final number
MATH_NAME = "churro_math.inc"
DEST_C = "arch/x86/kernel/gbos_vexemu.c"

KCONFIG_ANCHOR = "config X86_IOPL_IOPERM\n"
KCONFIG_ENTRY = '''config GBOS_VEXEMU
	bool "Emulate GFNI/VAES/VPCLMULQDQ/AVX-VNNI/AVX-IFMA/SHA-NI on #UD (for CPUs lacking them)"
	depends on X86_64 && PREEMPT_RCU
	default n
	help
	  Built-in version of the gbos_vexemu module: catches the invalid-opcode trap
	  of 64-bit user code, emulates the instruction and resumes. Needed to run
	  userland built for newer Intel cores (GoogleBook OS) on older CPUs such as
	  Amber Lake; active before the first userland process, which a module is not.
	  Each emulated instruction costs a trap. Does nothing on a CPU that has the
	  instructions. Command line: gbos_vexemu.enabled=0 turns it off.

	  If unsure, say N.

'''
MAKE_ANCHOR = "obj-y\t\t\t+= traps.o idt.o irq.o irq_$(BITS).o dumpstack_$(BITS).o\n"
MAKE_LINE = "obj-$(CONFIG_GBOS_VEXEMU)\t+= gbos_vexemu.o\n"


def die(m):
    sys.exit("gbos-vexemu-builtin: " + m)


def sha(b):
    return hashlib.sha256(b).hexdigest()


def load_module_tool():
    spec = importlib.util.spec_from_file_location("gbos_vexemu_tool", os.path.join(KDIR, "gbos-vexemu.py"))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)           # defines functions only; main() is guarded by __name__
    return m


def derive_c():
    src = open(SRC_C, encoding="utf-8").read()
    old = "module_init(vexemu_init);"
    if src.count(old) != 1:
        die("expected exactly one %r in %s; the module source changed, review this generator" % (old, SRC_C))
    out = src.replace(old, "/* built in: level 3, i.e. before every device/rootfs initcall and long before the first user process */\n"
                           "arch_initcall(vexemu_init);")
    guard = ('#if !__has_include("%s")\n#error "gbos_vexemu: %s is missing; run gbos-vexemu-builtin.py apply (it is third-party and kept out of the patch)"\n#endif\n' % (MATH_NAME, MATH_NAME))
    inc = '#include "%s"\n' % MATH_NAME
    if out.count(inc) != 1:
        die("expected exactly one include of %s" % MATH_NAME)
    out = out.replace(inc, guard + inc)
    banner = ("/* GENERATED by kernel/builtin/gbos-vexemu-builtin.py from kernel/vexemu/gbos_vexemu.c (sha256 %s).\n"
              " * Built-in variant; do not edit here, edit the module source and regenerate. */\n" % sha(src.encode())[:16])
    lines = out.split("\n", 1)                 # keep the SPDX line first
    return lines[0] + "\n" + banner + lines[1]


def udiff(path, old, new):
    a = old.splitlines(keepends=True)
    b = new.splitlines(keepends=True)
    d = list(difflib.unified_diff(a, b, "a/" + path if old else "/dev/null", "b/" + path, n=3))
    if not d:
        die("no change for " + path)
    head = "diff --git a/%s b/%s\n" % (path, path)
    if not old:
        head += "new file mode 100644\n"
    return head + "".join(l if l.endswith("\n") else l + "\n\\ No newline at end of file\n" for l in d)


def insert_before(text, anchor, ins, what):
    if text.count(anchor) != 1:
        die("anchor for %s not found exactly once in the tree (%r); the tree differs from 7.2.x, review" % (what, anchor.strip()))
    return text.replace(anchor, ins + anchor)


def insert_after(text, anchor, ins, what):
    if text.count(anchor) != 1:
        die("anchor for %s not found exactly once in the tree (%r)" % (what, anchor.strip()))
    return text.replace(anchor, anchor + ins)


def build_patch(tree):
    kc = open(os.path.join(tree, "arch/x86/Kconfig"), encoding="utf-8").read()
    mk = open(os.path.join(tree, "arch/x86/kernel/Makefile"), encoding="utf-8").read()
    if "GBOS_VEXEMU" in kc or "gbos_vexemu" in mk:
        die("the tree already carries GBOS_VEXEMU; generate against a clean tree")
    kc2 = insert_before(kc, KCONFIG_ANCHOR, KCONFIG_ENTRY, "Kconfig")
    mk2 = insert_after(mk, MAKE_ANCHOR, MAKE_LINE, "Makefile")
    return (udiff("arch/x86/Kconfig", kc, kc2) + udiff("arch/x86/kernel/Makefile", mk, mk2) + udiff(DEST_C, "", derive_c()))


def dry_run(tree, patch_text):
    with tempfile.NamedTemporaryFile("w", suffix=".patch", delete=False) as f:
        f.write(patch_text)
        name = f.name
    try:
        r = subprocess.run(["patch", "-p1", "--dry-run", "--no-backup-if-mismatch", "-d", tree, "-i", name],
                           capture_output=True, text=True)
    finally:
        os.unlink(name)
    if r.returncode != 0:
        die("the patch does not apply to %s:\n%s%s" % (tree, r.stdout, r.stderr))
    return r.stdout


def cmd_gen(a):
    os.makedirs(a.out, exist_ok=True)
    tool = load_module_tool()
    math = tool.extract_math(tool.get_patch(a.patch, a.out))          # refuses anything but the pinned patch
    text = build_patch(a.tree)
    print(dry_run(a.tree, text).rstrip())
    open(os.path.join(a.out, PATCH_NAME), "w").write(text)
    open(os.path.join(a.out, MATH_NAME), "w").write(math)
    print("wrote %s (%d bytes, our code only) and %s (%d bytes, third-party arithmetic, do not commit)" %
          (PATCH_NAME, len(text), MATH_NAME, len(math)))


def cmd_apply(a):
    p = os.path.join(a.out, PATCH_NAME)
    m = os.path.join(a.out, MATH_NAME)
    for f in (p, m):
        if not os.path.isfile(f):
            die("missing " + f + " (run gen first)")
    dry_run(a.tree, open(p).read())
    subprocess.run(["patch", "-p1", "--no-backup-if-mismatch", "-d", a.tree, "-i", os.path.abspath(p)], check=True)
    shutil.copyfile(m, os.path.join(a.tree, "arch/x86/kernel", MATH_NAME))
    print("applied; set CONFIG_GBOS_VEXEMU=y")


def cmd_check(a):
    ok = True
    for rel, needle in (("arch/x86/Kconfig", "config GBOS_VEXEMU"), ("arch/x86/kernel/Makefile", "gbos_vexemu.o"),
                        (DEST_C, "arch_initcall(vexemu_init)"), ("arch/x86/kernel/" + MATH_NAME, "churro_")):
        p = os.path.join(a.tree, rel)
        good = os.path.isfile(p) and needle in open(p, encoding="utf-8", errors="replace").read()
        print("%-4s %s" % ("ok" if good else "FAIL", rel))
        ok &= good
    sys.exit(0 if ok else 1)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("gen")
    g.add_argument("--tree", required=True)
    g.add_argument("--out", required=True)
    g.add_argument("--patch", help="local copy of the pinned vex-emulate.patch (otherwise downloaded and sha256-checked)")
    g.set_defaults(fn=cmd_gen)
    p = sub.add_parser("apply")
    p.add_argument("--tree", required=True)
    p.add_argument("--out", required=True)
    p.set_defaults(fn=cmd_apply)
    c = sub.add_parser("check")
    c.add_argument("--tree", required=True)
    c.set_defaults(fn=cmd_check)
    a = ap.parse_args()
    a.fn(a)


if __name__ == "__main__":
    main()
