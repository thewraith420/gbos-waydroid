#!/usr/bin/env python3
"""Generate server-side Binder dispatch (Dispatch.java) for the AIDL HAL interfaces whose Stub was stripped from the shaded service-wifi copy.
The client Proxy in the same source file tells us, per method, the transaction code, how arguments are written and how the result is read;
this inverts that. usage: gen_dispatch.py <aidl-src-dir> <out.java> <package> <Iface>..."""
import glob, os, re, sys

src, out, pkg = sys.argv[1], sys.argv[2], sys.argv[3]
ifaces = sys.argv[4:]
HAL = "com.android.wifi.x.android.hardware.wifi"

# simple type name -> fully qualified (top-level classes by file name; nested Parcelables as Outer.Nested)
fq = {}
for p in glob.glob(src + "/*.java"):
    n = os.path.basename(p)[:-5]
    if "$" in n: continue
    fq[n] = HAL + "." + n
    for m in re.finditer(r"\n    public (?:abstract )?(?:class|interface) (\w+)", open(p).read()):
        if m.group(1) != n and m.group(1) not in ("Stub", "Proxy"): fq[m.group(1)] = HAL + "." + n + "." + m.group(1)
for p in glob.glob(src + "/common/*.java"):
    n = os.path.basename(p)[:-5]; fq[n] = HAL + ".common." + n

def ft(t):
    t = t.strip()
    if t.endswith("[]"): return ft(t[:-2]) + "[]"
    return fq.get(t, t)

def base(t): return t[:-2] if t.endswith("[]") else t

def read_expr(stmt, ptype):
    m = re.match(r"obtain\.(\w+)\((.*)\);", stmt)
    op = m.group(1)
    T = ft(ptype)
    if op == "writeInt": return "(%s) data.readInt()" % T if ptype in ("byte", "char", "short") else "data.readInt()"
    if op == "writeLong": return "data.readLong()"
    if op == "writeBoolean": return "data.readBoolean()"
    if op == "writeByte": return "data.readByte()"
    if op == "writeString": return "data.readString()"
    if op == "writeByteArray": return "data.createByteArray()"
    if op == "writeIntArray": return "data.createIntArray()"
    if op == "writeTypedObject": return "(%s) data.readTypedObject(%s.CREATOR)" % (T, T)
    if op == "writeTypedArray": return "(%s) data.createTypedArray(%s.CREATOR)" % (T, ft(base(ptype)) + "")
    if op == "writeFixedArray":
        dims = [a.strip() for a in m.group(2).split(",")][2:]
        return "(%s) data.createFixedArray(%s.class, %s)" % (T, T, ", ".join(dims))
    if op == "writeStrongInterface" and ptype.endswith("Callback"):
        return "com.gbos.fakewifi.Callbacks.wrap(%s.class, data.readStrongBinder())" % T
    if op == "writeStrongInterface": return "%s.Stub.asInterface(data.readStrongBinder())" % T
    raise SystemExit("unhandled write op " + op + " in " + stmt)

def write_expr(body, ret):
    if ret == "void": return None
    if "readStrongBinder" in body: return "reply.writeStrongInterface(r);"
    fm0 = re.search(r"obtain2\.createFixedArray\([^,]+, ([^)]*)\)", body)
    if fm0: return "reply.writeFixedArray(r, android.os.Parcelable.PARCELABLE_WRITE_RETURN_VALUE, %s);" % fm0.group(1)
    m = re.search(r"obtain2\.(readInt|readString|readBoolean|readByte|readLong|createStringArray|createByteArray|createIntArray)\(\)", body)
    if m:
        return {"readInt": "reply.writeInt(r);", "readString": "reply.writeString(r);", "readBoolean": "reply.writeBoolean(r);", "readByte": "reply.writeByte(r);",
                "readLong": "reply.writeLong(r);", "createStringArray": "reply.writeStringArray(r);", "createByteArray": "reply.writeByteArray(r);",
                "createIntArray": "reply.writeIntArray(r);"}[m.group(1)]
    fm = re.search(r"obtain2\.createFixedArray\([^,]+, ([^)]*)\)", body)
    if fm: return "reply.writeFixedArray(r, android.os.Parcelable.PARCELABLE_WRITE_RETURN_VALUE, %s);" % fm.group(1)
    if "readTypedObject" in body: return "reply.writeTypedObject(r, android.os.Parcelable.PARCELABLE_WRITE_RETURN_VALUE);"
    if "createTypedArray" in body: return "reply.writeTypedArray(r, android.os.Parcelable.PARCELABLE_WRITE_RETURN_VALUE);"
    raise SystemExit("cannot work out result marshalling for " + ret)

o = ["package %s;\n" % pkg, "/* GENERATED by tools/gen_dispatch.py - do not edit */", "@SuppressWarnings(\"unchecked\")", "public final class Dispatch {", "    private Dispatch() {}\n"]
for ifc in ifaces:
    text = open("%s/%s.java" % (src, ifc)).read()
    prox = text[text.index("static final class Proxy"):]
    ms = list(re.finditer(r"\n            public ([\w.\[\]]+) (\w+)\(([^)]*)\) throws android\.os\.RemoteException \{\n(.*?)\n            \}\n", prox, re.S))
    o.append("    public static boolean %s(%s.%s impl, int code, android.os.Parcel data, android.os.Parcel reply) throws android.os.RemoteException {" % (ifc, HAL, ifc))
    o.append("        if (code >= 1 && code <= 16777215) data.enforceInterface(%s.%s.DESCRIPTOR);" % (HAL, ifc))
    o.append("        switch (code) {")
    count = 0
    for m in ms:
        ret, name, params, body = m.group(1), m.group(2), m.group(3), m.group(4)
        if name in ("getInterfaceVersion", "getInterfaceHash"): continue
        tm = re.search(r"transact\((\d+),", body)
        if not tm: continue
        pl = [p.strip().rsplit(" ", 1) for p in params.split(",") if p.strip()]
        writes = [l.strip() for l in body.split("\n") if re.match(r"\s*obtain\.write", l) and "writeInterfaceToken" not in l]
        if len(writes) != len(pl): raise SystemExit("%s.%s: %d writes vs %d params" % (ifc, name, len(writes), len(pl)))
        o.append("            case %s: { // %s" % (tm.group(1), name))
        for i, ((pt, _), w) in enumerate(zip(pl, writes)):
            o.append("                %s p%d = %s;" % (ft(pt), i, read_expr(w, pt)))
        call = "impl.%s(%s)" % (name, ", ".join("p%d" % i for i in range(len(pl))))
        we = write_expr(body, ret)
        if we is None:
            o.append("                %s;" % call)
            o.append("                reply.writeNoException();")
        else:
            o.append("                %s r = %s;" % (ft(ret), call))
            o.append("                reply.writeNoException();")
            o.append("                " + we)
        o.append("                return true; }")
        count += 1
    o.append("            default: return false;")
    o.append("        }\n    }\n")
    print(ifc, count, "methods")
o.append("}")
open(out, "w").write("\n".join(o) + "\n")
