#!/usr/bin/env python3
"""Generate default implementations (Def<Name> extends <Iface>.Stub) for AIDL interfaces, from `javap` output.
usage: gen_defaults.py <classpath> <out.java> <package> <FQCN>[=Name] ...
Every method returns a zero value (0/false/""/empty array/null); real behaviour is added by subclassing in hand-written code."""
import re, subprocess, sys

cp, out, pkg = sys.argv[1], sys.argv[2], sys.argv[3]
specs = sys.argv[4:]
SIG = re.compile(r"^\s+public abstract (?P<ret>[\w.$\[\]<>?, ]+?) (?P<name>\w+)\((?P<args>[^)]*)\)(?: throws [\w.$, ]+)?;$")

def jn(t):                      # javap type -> Java source type
    return t.replace("$", ".")

def default(ret):
    if ret == "void": return ""
    if ret == "boolean": return "return false;"
    if ret in ("byte", "short", "char", "int", "long", "float", "double"): return "return 0;"
    if ret == "java.lang.String": return 'return "";'
    if ret.endswith("[]"): return "return new %s[0];" % jn(ret[:-2])
    # Parcelable results of the Wi-Fi HAL must never be null: system_server dereferences them (e.g. StaApfPacketFilterCapabilities.version,
    # which crashed system_server once a connection was attempted). Interfaces (I[A-Z]...) stay null, hand-written code supplies those.
    if ret.startswith("com.android.wifi.x.android.hardware.wifi.") and not re.match(r"I[A-Z]", ret.rsplit(".", 1)[1]):
        return "return new %s();" % jn(ret)
    return "return null;"

body = ["package %s;\n" % pkg, "/* GENERATED by tools/gen_defaults.py - do not edit */", "@SuppressWarnings(\"unchecked\")", "public final class Defaults {", "    private Defaults() {}\n"]
for spec in specs:
    ctor = spec.endswith("+ctor")           # jadx dropped the Stub constructor of some AIDL classes: re-create it
    spec = spec[:-5] if ctor else spec
    fq, _, nick = spec.partition("=")
    nick = nick or fq.rsplit(".", 1)[1]
    txt = subprocess.run(["javap", "-cp", cp, fq], capture_output=True, text=True, check=True).stdout
    body.append("    public static abstract class Def%s extends %s.Stub {" % (nick, jn(fq)))
    seen = set()
    if ctor:
        body.append("        protected Def%s() { markVintfStability(); attachInterface(this, %s.DESCRIPTOR); }" % (nick, jn(fq)))
        body.append("        public int getInterfaceVersion() { return 4; }")
        body.append("        public String getInterfaceHash() { return \"fake\"; }")
        body.append("        @Override protected boolean onTransact(int code, android.os.Parcel data, android.os.Parcel reply, int flags) throws android.os.RemoteException {")
        body.append("            if (code == 16777215) { data.enforceInterface(%s.DESCRIPTOR); reply.writeNoException(); reply.writeInt(getInterfaceVersion()); return true; }" % jn(fq))
        body.append("            if (code == 16777214) { data.enforceInterface(%s.DESCRIPTOR); reply.writeNoException(); reply.writeString(getInterfaceHash()); return true; }" % jn(fq))
        body.append("            if (Dispatch.%s(this, code, data, reply)) return true;" % nick)
        body.append("            return super.onTransact(code, data, reply, flags);")
        body.append("        }")
        seen.update({("getInterfaceVersion", 0), ("getInterfaceHash", 0)})
    body.append("        @Override public android.os.IBinder asBinder() { return this; }")
    for line in txt.splitlines():
        m = SIG.match(line)
        if not m: continue
        name, ret, args = m.group("name"), m.group("ret"), [a.strip() for a in m.group("args").split(",") if a.strip()]
        if name in ("asBinder", "onTransact") or (name, len(args)) in seen: continue
        seen.add((name, len(args)))
        params = ", ".join("%s a%d" % (jn(t), i) for i, t in enumerate(args))
        d = default(ret)
        body.append('        @Override public %s %s(%s) throws android.os.RemoteException { android.util.Log.d("FAKEWIFI", "%s.%s"); %s }' % (jn(ret), name, params, nick, name, d))
    body.append("    }\n")
body.append("}")
open(out, "w").write("\n".join(body) + "\n")
print("wrote", out)
